// Builds the single-file drop-ins into dist/dropin/, for installing by copy and paste (no npm package needed):
//
//   notify-server.mjs + notify-server.d.mts   the embeddable server; the only dependency is `ws`
//   notify-web.tsx                            the React/TypeScript client; needs `react` and `sonner`
//
// They are generated from packages/server and packages/web. Don't edit them: change the source and rebuild.
// Run:  npm run dropin      Verify the output actually works:  npm run dropin:verify

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const out = path.join(root, 'dist', 'dropin');
mkdirSync(out, { recursive: true });

const read = (...p) => readFileSync(path.join(root, ...p), 'utf8').replace(/\r\n/g, '\n');
const version = (pkgDir) => JSON.parse(read(pkgDir, 'package.json')).version;

// MIT requires the notice to stay with "all copies or substantial portions", and these files are copies meant to be
// pasted into other projects. So each carries the full text of ./LICENSE in its header (read from that file, so the
// two cannot drift apart).
const licenseText = read('LICENSE').trim();
const licenseComment = licenseText.split('\n').map((l) => (l ? `// ${l}` : '//')).join('\n');

const banner = (name, version, extra = '') =>
  `// ${name} v${version}: single-file drop-in, generated by tools/dropin/build.mjs from packages/.\n` +
  `// Do not edit this copy; change the source and regenerate. ${extra}`.trimEnd() + '\n' +
  `//\n${licenseComment}\n`;

// ---------------------------------------------------------------- server

const serverVersion = version('packages/server');
const serverBanner = banner('notify-server', serverVersion, 'Needs: npm install ws (ES module; Node 18+).');

await build({
  entryPoints: [path.join(root, 'packages/server/index.js')],
  outfile: path.join(out, 'notify-server.mjs'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node18',
  external: ['ws'], // the one dependency you install yourself
  legalComments: 'none',
  banner: { js: serverBanner.trimEnd() },
  logLevel: 'warning',
});

// `.d.mts` is the declaration file TypeScript pairs with an `.mjs` module.
writeFileSync(path.join(out, 'notify-server.d.mts'), serverBanner + read('packages/server/index.d.ts'));

// ---------------------------------------------------------------- web client

const webVersion = version('packages/web');
const types = read('packages/web/src/types.ts');
let hook = read('packages/web/src/useHub.tsx');

// The hook's three imports are replaced by one header; anything left over means the source changed shape.
const IMPORTS = /^import .*from '(react|sonner|\.\/types)';\n/gm;
hook = hook.replace(IMPORTS, '');
if (/^import /m.test(hook)) {
  throw new Error('packages/web/src/useHub.tsx has an import this script does not know how to inline; update build.mjs');
}

writeFileSync(
  path.join(out, 'notify-web.tsx'),
  banner('notify-web', webVersion, 'Needs: react (18+) and sonner. Copy into your app, e.g. src/notify-web.tsx.') +
    "\nimport { useCallback, useEffect, useRef, useState } from 'react';\nimport { toast } from 'sonner';\n\n" +
    types +
    '\n' +
    hook
);

console.log(`dropin v${serverVersion}: wrote notify-server.mjs, notify-server.d.mts, notify-web.tsx -> ${path.relative(root, out)}`);
